// Compile writes the chart a ChartSpec describes into dir: Chart.yaml,
// values.yaml, a closed values.schema.json, the Bundt Package with its
// outputs, one template per resource, a README, and the spec itself
// (chartspec.yaml, left out of the packaged chart) so the chart can be
// regenerated when the compiler improves.
func Compile(spec *ChartSpec, dir string) error {
	if err := os.MkdirAll(filepath.Join(dir, "templates"), 0o755); err != nil {
		return err
	}
	files := map[string][]byte{}

	chart := map[string]any{
		"apiVersion":  "v2",
		"name":        spec.Chart.Name,
		"description": spec.Chart.Description,
		"type":        "application",
		"version":     spec.Chart.Version,
		"keywords":    []any{"gcp", "config-connector", "composed", "terraform-offramp"},
		"annotations": map[string]any{
			"hfl.dev/composed-by":         "offramp compose",
			"hfl.dev/chartspec":           ChartSpecAPIVersion,
			"hfl.dev/source-kind":         spec.Source.Kind,
			"hfl.dev/source-call":         orDefault(spec.Source.Call, "root"),
			"hfl.dev/source-tool":         orDefault(spec.Source.Tool, "unknown"),
			"hfl.dev/source-form":         spec.Source.Form,
			"hfl.dev/source-tool-version": spec.Source.TerraformVersion,
			"hfl.dev/source-resources":    strconv.Itoa(len(spec.Source.Addresses)),
		},
	}
	b, err := yaml.Marshal(chart)
	if err != nil {
		return err
	}
	files["Chart.yaml"] = append([]byte(header("#")), b...)

	values := map[string]any{}
	for _, v := range spec.Values {
		values[v.Name] = v.Default
	}
	files["values.yaml"] = valuesYAML(spec)

	schema := valuesSchema(spec)
	if files["values.schema.json"], err = json.MarshalIndent(schema, "", "  "); err != nil {
		return err
	}

	outs := map[string]any{}
	for _, o := range spec.Outputs {
		outs[o.Name] = o.Value
	}
	pkg := map[string]any{
		"apiVersion": "hfl.dev/v1",
		"kind":       "Package",
		"metadata":   map[string]any{"name": "gcp-" + spec.Chart.Name},
		"spec": map[string]any{
			"version":   spec.Chart.Version,
			"engine":    "helm",
			"providers": []any{"kcc"},
			"outputs":   outs,
		},
	}
	if b, err = yaml.Marshal(pkg); err != nil {
		return err
	}
	files["package.yaml"] = append([]byte(header("#")), b...)

	nameDefaults := map[string]string{}
	for _, r := range spec.Resources {
		nameDefaults[r.ID] = r.NameDefault
	}
	for _, r := range spec.Resources {
		t, err := template(r.Object, nameDefaults)
		if err != nil {
			return fmt.Errorf("%s: %w", r.ID, err)
		}
		files[filepath.Join("templates", r.ID+".yaml")] = append([]byte(header("#")), t...)
	}

	if b, err = yaml.Marshal(spec); err != nil {
		return err
	}
	files["chartspec.yaml"] = append([]byte("# The ChartSpec this chart was compiled from. Edit this, not the templates,\n# and compile again.\n"), b...)
	files[".helmignore"] = []byte("chartspec.yaml\nverify.md\n")
	files["README.md"] = []byte(readme(spec))

	for name, data := range files {
		if err := os.WriteFile(filepath.Join(dir, name), data, 0o644); err != nil {
			return err
		}
	}
	return nil
}

func header(c string) string {
	return c + " Copyright 2026 High Five Labs\n" + c + " SPDX-License-Identifier: Apache-2.0\n" + c + " Generated by `offramp compose` from chartspec.yaml: do not edit.\n"
}

func orDefault(s, d string) string {
	if s == "" {
		return d
	}
	return s
}

func valuesYAML(spec *ChartSpec) []byte {
	var b bytes.Buffer
	b.WriteString(header("#"))
	tier := ""
	for _, v := range orderedValues(spec) {
		if v.Tier != tier {
			tier = v.Tier
			fmt.Fprintf(&b, "\n# --- %s ---\n", map[string]string{TierPlacement: "Standard placement block (Bundt fills these from the StackInstance)", TierKnob: "Knobs", TierAdoption: "Adoption", TierOverride: "Overrides (escape hatches)"}[tier])
		}
		fmt.Fprintf(&b, "\n# %s", v.Description)
		if v.Identity {
			b.WriteString(" Changing it recreates resources.")
		}
		b.WriteString("\n")
		y, _ := yaml.Marshal(map[string]any{v.Name: v.Default})
		b.Write(y)
	}
	return b.Bytes()
}

func orderedValues(spec *ChartSpec) []SpecValue {
	rank := map[string]int{TierPlacement: 0, TierKnob: 1, TierAdoption: 2, TierOverride: 3}
	vs := append([]SpecValue(nil), spec.Values...)
	sort.SliceStable(vs, func(i, j int) bool { return rank[vs[i].Tier] < rank[vs[j].Tier] })
	return vs
}

func valuesSchema(spec *ChartSpec) map[string]any {
	props := map[string]any{}
	var required []any
	for _, v := range spec.Values {
		p := map[string]any{"type": v.Type, "description": v.Description}
		if v.Name == "names" {
			var ids []any
			for _, r := range spec.Resources {
				if r.NameDefault != "" {
					ids = append(ids, r.ID)
				}
			}
			p["additionalProperties"] = map[string]any{"type": "string", "minLength": 1}
			p["propertyNames"] = map[string]any{"enum": ids}
		}
		if v.Name == "labels" || v.Name == "resourceIds" {
			p["additionalProperties"] = map[string]any{"type": "string"}
		}
		if v.Name == "deletionPolicy" {
			p["enum"] = []any{"abandon", "delete"}
		}
		if v.Type == "integer" || v.Type == "number" {
			p["type"] = []any{"integer", "number"}
		}
		props[v.Name] = p
		required = append(required, v.Name)
	}
	return map[string]any{
		"$schema":              "https://json-schema.org/draft-07/schema#",
		"type":                 "object",
		"additionalProperties": false,
		"required":             required,
		"properties":           props,
	}
}

var nameRE = regexp.MustCompile(`^\$\{name\.([^}]+)\}$`)

var adoptRE = regexp.MustCompile(`^\$\{resourceIds\.([^}]+)\}$`)

var valueRefRE = regexp.MustCompile(`\$\{values\.([A-Za-z0-9_]+)\}`)

// template turns a resource into a Helm template: the object as YAML, with
// each bound field replaced by a Go template expression rendering JSON
// (valid YAML in flow style), so types survive.
func template(obj map[string]any, nameDefaults map[string]string) ([]byte, error) {
	exprs := map[string]string{}
	n := 0
	token := func(expr string) string {
		n++
		t := fmt.Sprintf("HFLTPL%06dX", n)
		exprs[t] = expr
		return t
	}
	var walk func(v any) any
	walk = func(v any) any {
		switch t := v.(type) {
		case map[string]any:
			if m, ok := t[mergeKey].(string); ok {
				name := valueRefRE.FindStringSubmatch(m)[1]
				var parts []string
				for _, k := range sortedKeys(t) {
					if k == mergeKey {
						continue
					}
					parts = append(parts, strconv.Quote(k), stringExpr(str(t[k])))
				}
				return token(fmt.Sprintf("{{ toJson (merge (dict %s) (.Values.%s | default dict)) }}", strings.Join(parts, " "), name))
			}
			for k, x := range t {
				t[k] = walk(x)
			}
			return t
		case []any:
			for i, x := range t {
				t[i] = walk(x)
			}
			return t
		case string:
			if m := nameRE.FindStringSubmatch(t); m != nil {
				return token(fmt.Sprintf("{{ index (.Values.names | default dict) %q | default %s | toJson }}", m[1], stringExpr(nameDefaults[m[1]])))
			}
			if m := adoptRE.FindStringSubmatch(t); m != nil {
				return token(fmt.Sprintf("{{ with index (.Values.resourceIds | default dict) %q }}{{ toJson . }}{{ end }}", m[1]))
			}
			if !strings.Contains(t, "${values.") {
				return t
			}
			if m := valueRefRE.FindStringSubmatch(t); m != nil && m[0] == t {
				return token(fmt.Sprintf("{{ toJson .Values.%s }}", m[1]))
			}
			return token(fmt.Sprintf("{{ %s | toJson }}", stringExpr(t)))
		}
		return v
	}
	c := walk(deepCopy(obj))
	b, err := yaml.Marshal(c)
	if err != nil {
		return nil, err
	}
	s := string(b)
	for t, e := range exprs {
		if !strings.Contains(s, t) {
			return nil, fmt.Errorf("lost template token %s", t)
		}
		s = strings.ReplaceAll(s, t, e)
	}
	return []byte(s), nil
}

// stringExpr is a template pipeline producing the string, interpolations
// included: (print "projects/" .Values.projectId "/x").
func stringExpr(s string) string {
	idx := valueRefRE.FindAllStringSubmatchIndex(s, -1)
	if len(idx) == 0 {
		return strconv.Quote(s)
	}
	var parts []string
	last := 0
	for _, m := range idx {
		if m[0] > last {
			parts = append(parts, strconv.Quote(s[last:m[0]]))
		}
		parts = append(parts, "(.Values."+s[m[2]:m[3]]+" | toString)")
		last = m[1]
	}
	if last < len(s) {
		parts = append(parts, strconv.Quote(s[last:]))
	}
	if len(parts) == 1 {
		return parts[0]
	}
	return "(print " + strings.Join(parts, " ") + ")"
}

func readme(spec *ChartSpec) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\n%s\n\nComposed from %d resources (%s %s, %s). Edit `chartspec.yaml` and compile again; the templates are generated.\n\n",
		spec.Chart.Name, spec.Chart.Description, len(spec.Source.Addresses), orDefault(spec.Source.Tool, "Terraform or OpenTofu"), spec.Source.TerraformVersion, spec.Source.Form)
	b.WriteString("## Values\n\n| Value | Tier | Default | Recreates | Description |\n| --- | --- | --- | --- | --- |\n")
	for _, v := range orderedValues(spec) {
		d, _ := json.Marshal(v.Default)
		rec := ""
		if v.Identity {
			rec = "yes"
		}
		fmt.Fprintf(&b, "| `%s` | %s | `%s` | %s | %s |\n", v.Name, v.Tier, d, rec, v.Description)
	}
	b.WriteString("\n## Resources\n\n| ID | Kind | Stateful |\n| --- | --- | --- |\n")
	for _, r := range spec.Resources {
		st := ""
		if r.Stateful {
			st = "yes (always abandoned)"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", r.ID, r.Kind, st)
	}
	if len(spec.Outputs) > 0 {
		b.WriteString("\n## Outputs\n\n")
		for _, o := range spec.Outputs {
			fmt.Fprintf(&b, "- `%s`: `%s`\n", o.Name, o.Value)
		}
	}
	if len(spec.Findings) > 0 {
		b.WriteString("\n## Findings\n\n")
		for _, f := range spec.Findings {
			if f.Resource != "" {
				fmt.Fprintf(&b, "- `%s`: %s\n", f.Resource, f.Reason)
			} else {
				fmt.Fprintf(&b, "- %s\n", f.Reason)
			}
		}
	}
	b.WriteString("\n## Source\n\n")
	for _, a := range spec.Source.Addresses {
		fmt.Fprintf(&b, "- `%s`\n", a)
	}
	return b.String()
}

// Verification is Verify's result.
type Verification struct {
	Chart       string
	Lint        string // "" when helm lint passed
	Differences []Difference
	// Collisions are identities two instances (different codenames, networks
	// and subnetworks, one project) would share.
	Collisions []string
	Err        string
}

// OK is a chart that lints and renders the state with no difference.
// Collisions are reported, not failed: an imported chart may keep a
// fixed name on purpose (a folder, a project).
func (v *Verification) OK() bool { return v.Err == "" && v.Lint == "" && len(v.Differences) == 0 }

// Verify lints the chart, renders it with its defaults and compares the
// render with the objects it was composed from, then renders three
// instances into one project and lists the names they share.
func Verify(spec *ChartSpec, dir string, objs []*Object) *Verification {
	v := &Verification{Chart: spec.Chart.Name}
	cmd := exec.Command("helm", "lint", dir)
	var out bytes.Buffer
	cmd.Stdout, cmd.Stderr = &out, &out
	if err := cmd.Run(); err != nil {
		v.Lint = strings.TrimSpace(out.String())
	}
	rendered, err := renderChart(dir, spec.Chart.Name, "", map[string]any{})
	if err != nil {
		v.Err = err.Error()
		return v
	}
	// The expected objects: the state's, with references inside the chart
	// in the same form the chart writes them (by name; Config Connector
	// resolves them to the same resource).
	want := make([]SpecRes, len(objs))
	for i, o := range objs {
		want[i] = SpecRes{Kind: o.Kind, Object: deepCopy(o.Obj).(map[string]any)}
	}
	internalRefs(want, false)
	var a, b []map[string]any
	for _, r := range rendered {
		a = append(a, r)
	}
	for _, w := range want {
		b = append(b, w.Object)
	}
	v.Differences = append(Compare(a, b), metaDiffs(a, b)...)

	// Collisions.
	seen := map[string]int{}
	for i, m := range []string{"zqa", "zqb", "zqc"} {
		// A new instance: its own codeName and names, no adopted IDs; its
		// own project when the chart makes the project.
		vals := map[string]any{"codeName": m}
		for _, sv := range spec.Values {
			if sv.Name == "resourceIds" {
				// Helm merges maps: null each key to clear it.
				cleared := map[string]any{}
				for k := range sv.Default.(map[string]any) {
					cleared[k] = nil
				}
				vals["resourceIds"] = cleared
			}
		}
		for _, r := range spec.Resources {
			if r.Kind == "Project" {
				vals["projectId"] = m + "-proj"
			}
		}
		for _, sv := range spec.Values {
			if (sv.Name == "network" || sv.Name == "subnetwork") && sv.Uses > 0 {
				vals[sv.Name] = fmt.Sprintf("%s-%d", sv.Default, i)
			}
		}
		objs, err := renderChart(dir, spec.Chart.Name, "", vals)
		if err != nil {
			v.Err = "collision render: " + err.Error()
			return v
		}
		for _, o := range objs {
			seen[scopedIdentity(o)]++
		}
	}
	for _, id := range sortedKeys(seen) {
		if seen[id] > 1 {
			v.Collisions = append(v.Collisions, id)
		}
	}
	return v
}

// metaDiffs compares what adoption also writes outside spec: labels (the
// cloud's labels) and the project.
func metaDiffs(a, b []map[string]any) []Difference {
	ib := map[string]map[string]any{}
	for _, o := range b {
		ib[Identity(o)] = o
	}
	var out []Difference
	for _, o := range a {
		id := Identity(o)
		w, ok := ib[id]
		if !ok {
			continue
		}
		la, _ := dig(o, "metadata", "labels").(map[string]any)
		lb, _ := dig(w, "metadata", "labels").(map[string]any)
		for _, k := range sortedKeys(mergeMaps(la, lb)) {
			if str(la[k]) != str(lb[k]) {
				out = append(out, Difference{id, "metadata.labels." + k, la[k], lb[k]})
			}
		}
		pa, pb := dig(o, "metadata", "annotations", annProject), dig(w, "metadata", "annotations", annProject)
		if str(pa) != str(pb) {
			out = append(out, Difference{id, "metadata.annotations." + annProject, pa, pb})
		}
	}
	return out
}

func mergeMaps(a, b map[string]any) map[string]any {
	out := map[string]any{}
	for k, v := range a {
		out[k] = v
	}
	for k, v := range b {
		out[k] = v
	}
	return out
}

// VerifyReport is the verification as markdown.
func VerifyReport(v *Verification) string {
	var b strings.Builder
	status := "**zero diff: the chart renders the state exactly**"
	if !v.OK() {
		status = "**not proven**"
	}
	fmt.Fprintf(&b, "# Verify: %s\n\n%s\n\n", v.Chart, status)
	if v.Err != "" {
		fmt.Fprintf(&b, "Error: %s\n\n", v.Err)
	}
	if v.Lint != "" {
		fmt.Fprintf(&b, "## helm lint\n\n```\n%s\n```\n\n", v.Lint)
	} else {
		b.WriteString("- helm lint: passed\n")
	}
	fmt.Fprintf(&b, "- differences from the state: %d\n", len(v.Differences))
	for _, d := range v.Differences {
		fmt.Fprintf(&b, "  - %s\n", d)
	}
	fmt.Fprintf(&b, "- collisions across three instances in one project: %d\n", len(v.Collisions))
	for _, c := range v.Collisions {
		fmt.Fprintf(&b, "  - %s\n", c)
	}
	return b.String()
}

// scopedIdentity is Identity plus the names of the objects it references by
// name: a node pool named "apps" in two clusters is two resources.
func scopedIdentity(o map[string]any) string {
	var refs []string
	walkStrings(o["spec"], "spec", func(path, s string) {
		if strings.HasSuffix(path, "Ref.name") {
			refs = append(refs, path+"="+s)
		}
	})
	sort.Strings(refs)
	if len(refs) == 0 {
		return Identity(o)
	}
	return Identity(o) + " [" + strings.Join(refs, " ") + "]"
}
